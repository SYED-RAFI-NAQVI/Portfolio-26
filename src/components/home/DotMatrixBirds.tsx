import React, { useMemo } from "react";
import styles from "./DotMatrixEnvironment.module.css";

const COLS = 25;
const ROWS = 19;

function getBirdGrid(variant: number) {
  const on = new Set<string>();
  const mid = new Set<string>();
  const dim = new Set<string>();
  const wing = new Set<string>();

  const key = (x: number, y: number) => `${x},${y}`;
  const add = (set: Set<string>, pts: number[][]) => pts.forEach(([x, y]) => set.add(key(x, y)));

  if (variant === 1) {
    add(on, [
      [18,7],[19,7],[20,7],[20,8],[19,8],[21,8],[22,8],
      [17,8],[17,9],[18,9],
      [12,9],[13,8],[14,8],[15,8],[16,8],
      [11,10],[12,10],[13,10],[14,10],[15,10],[16,10],[17,10],[18,10],
      [10,11],[11,11],[12,11],[13,11],[14,11],[15,11],[16,11],[17,11],
      [10,12],[11,12],[12,12],[13,12],[14,12],[15,12],[16,12],
      [11,13],[12,13],[13,13],[14,13],[15,13],
      [7,12],[8,12],[9,12],[6,13],[7,13],[8,13],[9,13],
      [5,14],[6,14],[7,14],[8,14],
      [13,7],[12,6],[11,5],[10,4],[9,3],[8,2],
      [12,7],[11,7],[10,6],[9,5],[8,4],[7,3],
      [11,8],[10,8],[9,7],[8,6],[7,5],[6,4],
      [10,9],[9,9],[8,8],[7,7],[6,6]
    ]);
    add(mid, [
      [14,9],[15,9],[16,9],[12,11],[14,11],[16,11],
      [11,12],[13,12],[15,12],[10,6],[9,5],[8,4],[7,5],[8,6],[9,7]
    ]);
    add(dim, [
      [19,7],[7,13],[6,14],[8,3],[7,4]
    ]);
    add(wing, [
      [13,7],[12,6],[11,5],[10,4],[9,3],[8,2],
      [12,7],[11,7],[10,6],[9,5],[8,4],[7,3],
      [11,8],[10,8],[9,7],[8,6],[7,5],[6,4]
    ]);
  }

  if (variant === 2) {
    add(on, [
      [18,8],[19,7],[20,7],[20,8],[19,8],[21,8],[22,8],
      [15,8],[16,8],[17,8],
      [12,9],[13,9],[14,9],[15,9],[16,9],[17,9],[18,9],
      [10,10],[11,10],[12,10],[13,10],[14,10],[15,10],[16,10],[17,10],
      [9,11],[10,11],[11,11],[12,11],[13,11],[14,11],[15,11],[16,11],
      [10,12],[11,12],[12,12],[13,12],[14,12],[15,12],
      [11,13],[12,13],[13,13],[14,13],
      [12,9],[11,8],[10,7],[9,6],[8,5],[7,5],
      [11,9],[10,8],[9,7],[8,6],[7,6],[6,6],
      [10,10],[9,9],[8,8],[7,7],[6,7],[5,7],
      [14,9],[15,8],[16,7],[17,6],[18,5],[19,5],
      [15,9],[16,8],[17,7],[18,6],[19,6],[20,6],
      [16,10],[17,9],[18,8],[19,7],[20,7],[21,7],
      [8,12],[7,12],[6,13],[5,13],[8,13],[7,13],[6,14],[5,14]
    ]);
    add(mid, [
      [13,10],[15,10],[12,11],[14,11],
      [9,7],[8,6],[7,6],[17,7],[18,6],[19,6],
      [7,13],[6,13]
    ]);
    add(dim, [
      [20,7],[11,12],[13,12],[6,14]
    ]);
    add(wing, [
      [11,8],[10,7],[9,6],[8,5],[7,5],
      [10,8],[9,7],[8,6],[7,6],[6,6],
      [15,8],[16,7],[17,6],[18,5],[19,5],
      [16,8],[17,7],[18,6],[19,6],[20,6]
    ]);
  }

  if (variant === 3) {
    add(on, [
      [17,8],[18,7],[19,7],[19,8],[18,8],[20,8],[21,8],
      [13,8],[14,8],[15,8],[16,8],
      [11,9],[12,9],[13,9],[14,9],[15,9],[16,9],[17,9],
      [10,10],[11,10],[12,10],[13,10],[14,10],[15,10],[16,10],
      [11,11],[12,11],[13,11],[14,11],[15,11],
      [12,10],[11,11],[10,12],[9,13],[8,14],
      [13,10],[12,11],[11,12],[10,13],[9,14],
      [15,10],[16,11],[17,12],[18,13],[19,14],
      [14,10],[15,11],[16,12],[17,13],[18,14],
      [8,10],[7,10],[6,11],[5,11],[7,11],[6,12],[5,12]
    ]);
    add(mid, [
      [13,9],[15,9],[12,10],[14,10],[10,12],[17,12],[6,11]
    ]);
    add(dim, [
      [19,7],[8,14],[19,14]
    ]);
    add(wing, [
      [11,11],[10,12],[9,13],[8,14],
      [16,11],[17,12],[18,13],[19,14]
    ]);
  }

  const dots = [];
  for (let y = 0; y < ROWS; y++) {
    for (let x = 0; x < COLS; x++) {
      const id = key(x, y);
      let classNames = styles.dot;
      
      if (on.has(id)) classNames += ` ${styles.dotOn}`;
      else if (mid.has(id)) classNames += ` ${styles.dotMid}`;
      else if (dim.has(id)) classNames += ` ${styles.dotDim}`;

      if (wing.has(id)) classNames += ` ${styles.wing}`;

      dots.push(<span key={id} className={classNames} />);
    }
  }
  return dots;
}

export type DotMatrixBirdsProps = {
  className?: string;
};

export function DotMatrixBirds({ className }: DotMatrixBirdsProps) {
  const pigeon1 = useMemo(() => getBirdGrid(1), []);
  const pigeon2 = useMemo(() => getBirdGrid(2), []);
  const pigeon3 = useMemo(() => getBirdGrid(3), []);

  return (
    <div className={`${styles.flock} ${className || ""}`} aria-hidden="true">
      <div className={`${styles.pigeon} ${styles.pigeon1}`}>{pigeon1}</div>
      <div className={`${styles.pigeon} ${styles.pigeon2}`}>{pigeon2}</div>
      <div className={`${styles.pigeon} ${styles.pigeon3}`}>{pigeon3}</div>
    </div>
  );
}
